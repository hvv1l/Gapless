function buildSmartExample(en, level) {
  const clean = en.toLowerCase();
  if (level === "A0" || level === "A1") {
    return `We often use "${clean}" in everyday English.`;
  }
  if (level === "A2" || level === "B1") {
    return `It is useful to know how to use "${clean}" in conversation.`;
  }
  return `Mastering the expression "${clean}" makes your ${level} speech sound natural.`;
}

