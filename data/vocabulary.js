function generateEnglishIPA(phrase) {
  if (!phrase) return "";
  const cleanPhrase = phrase.trim();
  const lower = cleanPhrase.toLowerCase();
  if (GAPLESS_IPA_DICTIONARY[lower]) {
    return `/${GAPLESS_IPA_DICTIONARY[lower]}/`;
  }
  const parts = lower.split(/\s+/).map(transcribeSingleWordToIPA).filter(Boolean);
  return parts.length > 0 ? `/${parts.join(" ")}/` : "";
}

window.generateEnglishIPA = generateEnglishIPA;

